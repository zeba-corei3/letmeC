/*
Doubling Series
Compute 1 + 2 + 4 + … + 2ⁿ. 
Print each partial sum and notice how fast it grows — 
and where your integer type overflows.
*/

#include <stdio.h>

int main()
{
    int n=0;
    printf("Enter n:: ");
    scanf("%d", &n);

    int dbl = 0;

    for(int i=1; i<=n; i++)
    {
        dbl += pow(2, i);
        printf("%d: %d\n", i, dbl);
    }

    return 0;

}


